-- =====================================================================
--  CyberClub, КР3. Начальная схема.
--  Основа — база из КР1 (clients, stations, bookings). Изменения для КР3:
--    * бронирование (основная сущность) получило UUID и отдельный номер;
--    * добавлены признак оплаты, архив, даты изменения и поле version;
--    * у клиентов и мест добавлены даты изменения и version.
-- =====================================================================

-- Нужно для ограничения "брони одного места не пересекаются" (EXCLUDE ... USING gist).
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- ---------------------------------------------------------------------
--  Клиенты
-- ---------------------------------------------------------------------
CREATE TABLE clients (
    id          BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nickname    VARCHAR(20)  NOT NULL UNIQUE,
    full_name   VARCHAR(100) NOT NULL,
    phone       VARCHAR(12)  NOT NULL UNIQUE,
    email       VARCHAR(100) NOT NULL UNIQUE,
    birth_date  DATE         NOT NULL,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version     BIGINT       NOT NULL DEFAULT 0,

    CONSTRAINT chk_clients_nickname   CHECK (nickname ~ '^[A-Za-z0-9_]{3,20}$'),
    CONSTRAINT chk_clients_phone      CHECK (phone ~ '^\+7[0-9]{10}$'),
    CONSTRAINT chk_clients_email      CHECK (email LIKE '%_@_%.__%'),
    CONSTRAINT chk_clients_birth_date CHECK (birth_date <= CURRENT_DATE)
);

-- ---------------------------------------------------------------------
--  Игровые места (справочник: включаются и отключаются, не удаляются)
-- ---------------------------------------------------------------------
CREATE TABLE stations (
    id           BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name         VARCHAR(20)   NOT NULL UNIQUE,
    type         VARCHAR(20)   NOT NULL,
    hourly_rate  NUMERIC(10,2) NOT NULL,
    specs        VARCHAR(255),
    active       BOOLEAN       NOT NULL DEFAULT TRUE,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version      BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT chk_stations_type CHECK (type IN ('STANDARD', 'VIP', 'BOOTCAMP', 'CONSOLE')),
    CONSTRAINT chk_stations_rate CHECK (hourly_rate > 0 AND hourly_rate <= 100000)
);

-- ---------------------------------------------------------------------
--  Бронирования (основная сущность)
-- ---------------------------------------------------------------------
CREATE TABLE bookings (
    id           UUID          PRIMARY KEY,
    number       BIGINT        GENERATED ALWAYS AS IDENTITY UNIQUE,
    client_id    BIGINT        NOT NULL,
    station_id   BIGINT        NOT NULL,
    start_time   TIMESTAMP     NOT NULL,
    end_time     TIMESTAMP     NOT NULL,
    status       VARCHAR(20)   NOT NULL DEFAULT 'CREATED',
    total_price  NUMERIC(10,2) NOT NULL,
    paid         BOOLEAN       NOT NULL DEFAULT FALSE,
    comment      VARCHAR(255),
    archived     BOOLEAN       NOT NULL DEFAULT FALSE,
    archived_at  TIMESTAMPTZ,
    created_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at   TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version      BIGINT        NOT NULL DEFAULT 0,

    CONSTRAINT fk_bookings_client  FOREIGN KEY (client_id)  REFERENCES clients(id)  ON DELETE RESTRICT,
    CONSTRAINT fk_bookings_station FOREIGN KEY (station_id) REFERENCES stations(id) ON DELETE RESTRICT,
    CONSTRAINT chk_bookings_status CHECK (status IN ('CREATED', 'CONFIRMED', 'ACTIVE', 'COMPLETED', 'CANCELLED')),
    CONSTRAINT chk_bookings_price  CHECK (total_price >= 0),
    CONSTRAINT chk_bookings_time   CHECK (end_time > start_time),
    CONSTRAINT chk_bookings_archive CHECK (archived = (archived_at IS NOT NULL)),
    -- Одно место не может быть занято двумя действующими бронями одновременно.
    -- Отменённые и архивные брони место не занимают.
    CONSTRAINT excl_bookings_overlap EXCLUDE USING gist (
        station_id WITH =,
        tsrange(start_time, end_time) WITH &&
    ) WHERE (status <> 'CANCELLED' AND NOT archived)
);

-- Индексы под поиск и фильтры
CREATE INDEX idx_bookings_start_time ON bookings (start_time);
CREATE INDEX idx_bookings_status     ON bookings (status);
CREATE INDEX idx_bookings_client     ON bookings (client_id);
CREATE INDEX idx_bookings_station    ON bookings (station_id);
CREATE INDEX idx_bookings_archived   ON bookings (archived);
CREATE INDEX idx_bookings_comment    ON bookings (lower(comment));
CREATE INDEX idx_clients_full_name   ON clients (lower(full_name));

COMMENT ON TABLE clients  IS 'Клиенты киберспортивного клуба';
COMMENT ON TABLE stations IS 'Игровые места клуба (справочник)';
COMMENT ON TABLE bookings IS 'Бронирования игровых мест (основная сущность)';
