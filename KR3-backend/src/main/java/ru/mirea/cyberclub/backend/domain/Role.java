package ru.mirea.cyberclub.backend.domain;

/**
 * Роли пользователей. Сервер проверяет их сам, независимо от того,
 * какие кнопки показывает клиент (JavaFX, Android, Swagger).
 * VIEWER, OPERATOR и ADMIN — сотрудники клуба; CLIENT — посетитель, он видит только свои данные.
 */
public enum Role {
    /** Просмотр клиентов, мест, броней и аналитики. */
    VIEWER("Просмотр"),
    /** Администратор зала: ведёт клиентов и бронирования. */
    OPERATOR("Администратор зала"),
    /** Полный доступ: справочник мест, окончательное удаление, пользователи системы. */
    ADMIN("Администратор системы"),
    /** Клиент клуба: вход на сайт, своя карточка и свои брони (/api/me/**). С ролями сотрудников не совмещается. */
    CLIENT("Клиент клуба");

    private final String title;

    Role(String title) {
        this.title = title;
    }

    public String getTitle() { return title; }
}
